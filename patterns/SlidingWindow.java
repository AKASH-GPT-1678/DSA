package patterns;

public class SlidingWindow {
    public static void main(String[] args) {
        System.out.println("Sliding Window");

    }
    public static int maxSum(int[] arr, int k){
        int max_sum = 0;
        for (int i = 0; i < k; i++) {
            max_sum += arr[i];
        }
        return 0;
    }
}
